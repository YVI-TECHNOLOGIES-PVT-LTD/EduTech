/**
 * Glossary helper to find an exact or case-insensitive match for a text term.
 */
export function lookupGlossary(term: string, targetLang: SupportedLanguageCode): string | null {
  if (!term || targetLang === 'en') return term;

  const cleanTerm = term.trim();

  // 1. Direct exact key match
  if (EDUTRACK_GLOSSARY[cleanTerm]?.[targetLang]) {
    return EDUTRACK_GLOSSARY[cleanTerm]![targetLang]!;
  }

  // 2. Case-insensitive key match
  const lowerTerm = cleanTerm.toLowerCase();
  for (const [key, translations] of Object.entries(EDUTRACK_GLOSSARY)) {
    if (key.toLowerCase() === lowerTerm && translations[targetLang]) {
      return translations[targetLang]!;
    }
  }

  return null;
}
